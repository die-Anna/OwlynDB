-- Testdaten für OwlynDB (PostgreSQL); läuft in der Datenbank "shop"
DROP SCHEMA IF EXISTS verkauf CASCADE;
DROP TABLE IF EXISTS public.bestellungen, public.kunden CASCADE;
DROP VIEW IF EXISTS public.v_umsatz;

CREATE TABLE public.kunden (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL CONSTRAINT uq_kunden_name UNIQUE,
  ort varchar(60),
  erstellt timestamp NOT NULL DEFAULT now(),
  aktiv boolean NOT NULL DEFAULT true,
  guthaben numeric(10,2),
  notiz text,
  avatar bytea,
  tags text[],
  extra jsonb
);
COMMENT ON COLUMN public.kunden.guthaben IS 'in CHF';
CREATE INDEX ix_kunden_ort ON public.kunden (ort);
CREATE INDEX ix_kunden_lower_name ON public.kunden (lower(name));

CREATE TABLE public.bestellungen (
  id bigserial PRIMARY KEY,
  kunde_id integer NOT NULL REFERENCES public.kunden (id),
  datum date NOT NULL,
  betrag numeric(12,2) NOT NULL CHECK (betrag >= 0),
  status text NOT NULL DEFAULT 'offen'
);


CREATE VIEW public.v_umsatz AS
SELECT k.ort, count(*) AS bestellungen, sum(b.betrag) AS summe
  FROM public.bestellungen b JOIN public.kunden k ON k.id = b.kunde_id
 GROUP BY k.ort;


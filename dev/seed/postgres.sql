CREATE OR REPLACE FUNCTION public.kunden_anzahl(p_ort text) RETURNS bigint
LANGUAGE plpgsql AS $$
BEGIN
  RAISE NOTICE 'Zähle Kunden in %', p_ort;
  RETURN (SELECT count(*) FROM public.kunden WHERE ort = p_ort);
END;
$$;

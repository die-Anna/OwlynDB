const label = (i: CompareItem) => `${i.status}:${i.kind}:${i.name}`;

async function main() {
  assertTestContainers(Object.entries(targets).map(([name, t]) => ({ name, host: '127.0.0.1', port: t.port })));
  const m = new Manager(store, undefined, 0);
  for (const dialect of ['mysql', 'postgres', 'mssql'] as const) {
    console.log(`\n${dialect}`);
    const t = targets[dialect];
    const c = await store.save({
      name: dialect,
      dialect,
      host: '127.0.0.1',
      port: t.port,
      user: t.user,
      password: t.password,
      database: t.admin,
      options: dialect === 'mssql' ? { trustServerCertificate: true } : {},
    });
    const run = async (db: string, sqls: string[]) => {
      const { sessionId } = await m.openSession(c.id, db);
      try {
        for (const sql of sqls) {
          const r = await m.runQuery(sessionId, [{ sql, offset: 0 }], 10);
          if (r.statements[0]?.error) throw new Error(`${sql.slice(0, 120)}: ${r.statements[0].error}`);
        }
      } finally {
        await m.closeSession(sessionId);
      }
    };
    for (const db of ['cmp_src', 'cmp_dst']) {
      if (dialect === 'mysql') await run(t.admin, [`DROP DATABASE IF EXISTS ${db}`, `CREATE DATABASE ${db}`]);
      if (dialect === 'postgres') await run(t.admin, [`DROP DATABASE IF EXISTS ${db} WITH (FORCE)`, `CREATE DATABASE ${db}`]);
      if (dialect === 'mssql') {
        await run(t.admin, [`IF DB_ID('${db}') IS NOT NULL BEGIN ALTER DATABASE [${db}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [${db}]; END`, `CREATE DATABASE [${db}]`]);
      }
    }
    await run('cmp_src', ddl[dialect].src);
    await run('cmp_dst', ddl[dialect].dst);
    const req = { source: { connectionId: c.id, database: 'cmp_src', schema: t.schema }, target: { connectionId: c.id, database: 'cmp_dst', schema: t.schema } };
    const routine = dialect === 'postgres' ? 'function:f_x' : 'procedure:p_x';
    let items: CompareItem[] = [];

    await step('Unterschiede erkannt', async () => {
      const r = await m.compareSchemas(req);
      items = r.items;
      const expected = [
        'different:table:best',
        'different:table:kunden',
        'different:table:pos',
        `different:${routine}`,
        'different:view:v_k',
        'onlySource:table:nur_quelle',
        'onlyTarget:table:nur_ziel',
        'onlyTarget:table:nur_ziel_kind',
        ...(dialect === 'mssql' ? ['onlySource:procedure:p_only'] : []),
      ];
      assert.deepEqual(items.map(label).sort(), expected.sort());
      const k = items.find((i) => i.name === 'kunden')!.details.join(' | ');
      for (const part of ['Spalte ort:', 'Spalte neu fehlt im Ziel', 'Spalte alt nur im Ziel', 'Index ix_ort fehlt im Ziel', 'Index ix_nur_ziel nur im Ziel', 'Index uq_name:', 'CHECK ck_qty fehlt im Ziel']) {
        assert.ok(k.includes(part), `${part} fehlt in: ${k}`);
      }
      assert.match(k, /Spalte qty: int(eger)? → bigint/);
      assert.match(k, /Spalte leer: Standard – → \(?N?''/);
      assert.match(items.find((i) => i.name === 'best')!.details.join(' | '), /Fremdschlüssel fk_best_kunde fehlt im Ziel/);
      assert.match(items.find((i) => i.name === 'pos')!.details.join(' | '), /Fremdschlüssel fk_pos_best unterschiedlich/);
      // Tabellen nur im Ziel: die verweisende zuerst (sonst scheiterte DROP TABLE nur_ziel am Fremdschlüssel)
      const only = items.filter((i) => i.status === 'onlyTarget' && i.kind === 'table').map((i) => i.name);
      assert.deepEqual(only, ['nur_ziel_kind', 'nur_ziel']);
      if (dialect === 'mssql') {
        // gespeicherte ALTER-Texte: das Skript legt mit CREATE OR ALTER an
        for (const n of ['p_x', 'p_only']) assert.match(items.find((i) => i.name === n)!.script.routines![0], /^CREATE OR ALTER PROCEDURE/m);
        assert.match(items.find((i) => i.name === 'v_k')!.script.views![0], /^CREATE OR ALTER VIEW/m);
      }
      assert.deepEqual(r.warnings, []);
    });

    await step('Skript: Löschungen standardmäßig auskommentiert', async () => {
      const s = compareScript(dialect, items, false);
      assert.match(s, /-- auskommentiert/);
      assert.ok(!/^DROP TABLE/m.test(s), 'DROP TABLE darf nicht aktiv sein');
      assert.match(s, /^-- DROP TABLE/m);
    });

    await step('Skript im Ziel ausführen (wie F5 im Abfrage-Tab) → danach keine Unterschiede', async () => {
      const script = compareScript(dialect, items, true);
      const { sessionId } = await m.openSession(c.id, 'cmp_dst');
      try {
        const stmts = splitSql(script, dialect).map((s) => ({ sql: s.sql, offset: s.start }));
        const r = await m.runQuery(sessionId, stmts, 10);
        const bad = r.statements.find((s) => s.error);
        assert.ok(!bad, `${bad?.sql}\n→ ${bad?.error}`);
      } finally {
        await m.closeSession(sessionId);
      }
      const again = await m.compareSchemas(req);
      assert.deepEqual(
        again.items.map((i) => `${label(i)}: ${i.details.join('; ')}`),
        [],
      );
      assert.ok(again.same >= 5, `gleich: ${again.same}`);
      // Fremdschlüssel-Regel und CHECK sind wirklich da
      const ref = (name: string) => ({ connectionId: c.id, database: 'cmp_dst', schema: t.schema, name, kind: 'table' as const });
      const pos = await m.describeTable(ref('pos'));
      assert.equal(pos.foreignKeys[0]?.onDelete, 'CASCADE');
      const k = await m.describeTable(ref('kunden'));
      assert.ok(k.checks?.some((x) => x.name === 'ck_qty'), JSON.stringify(k.checks));
      assert.deepEqual(k.indexes.find((i) => i.name === 'uq_name')?.columns, ['name']);
    });

    if (dialect !== 'mysql') {
      await step('anderes Ziel-Schema: Skript wirkt im Ziel-Schema, nicht in der Quelle (Routinen, Views, Fremdschlüssel)', async () => {
        const s2 = { ...req, target: { ...req.target, schema: 's2' } };
        await run('cmp_dst', ['CREATE SCHEMA s2']);
        const r = await m.compareSchemas(s2);
        assert.ok(r.items.every((i) => i.status === 'onlySource'), r.items.map(label).join(', '));
        const script = compareScript(dialect, r.items, true);
        assert.ok(!new RegExp(`(FUNCTION|PROCEDURE|VIEW)\\s+(\\[?${t.schema}\\]?)\\.`, 'i').test(script), script);
        const { sessionId } = await m.openSession(c.id, 'cmp_dst');
        try {
          const stmts = splitSql(script, dialect).map((x) => ({ sql: x.sql, offset: x.start }));
          const rr = await m.runQuery(sessionId, stmts, 10);
          const bad = rr.statements.find((x) => x.error);
          assert.ok(!bad, `${bad?.sql}\n→ ${bad?.error}`);
        } finally {
          await m.closeSession(sessionId);
        }
        const again = await m.compareSchemas(s2);
        assert.deepEqual(again.items.map((i) => `${label(i)}: ${i.details.join('; ')}`), []);
      });
    }

    await step('verschiedene Datenbanktypen: abgelehnt', async () => {
      const other = await store.save({ name: 'x', dialect: dialect === 'mysql' ? 'postgres' : 'mysql', host: '127.0.0.1', port: 1, user: 'x', options: {} });
      await assert.rejects(m.compareSchemas({ ...req, target: { ...req.target, connectionId: other.id } }), /desselben Typs/);
    });
  }
  await m.shutdown();
  console.log(failed ? `\n${failed} Fehler` : '\nalles ok');
  process.exit(failed ? 1 : 0);
}

void main();

/* Schema-Vergleich: Unterschiede erkennen, Abgleich-Skript ausführen, danach muss alles gleich sein.
   Vorher: npm run testdb:up. Aufruf: npm run test:compare */
import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { CompareItem, SqlDialect } from '../../shared/api-types';

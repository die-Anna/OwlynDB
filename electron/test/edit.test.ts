import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { ConnectionInput, SqlDialect, ObjectRef, RowChange } from '../../shared/api-types';
import { ConnectionStore } from '../connection-store';
import { Manager } from '../manager';
import { assertTestContainers } from './guard';

const store = new ConnectionStore(path.join(mkdtempSync(path.join(os.tmpdir(), 'dbv-edit-')), 'c.json'), {
  encrypt: (s) => 'x' + s,
  decrypt: (s) => s.slice(1),
});

let failed = 0;
async function step(name: string, fn: () => Promise<unknown>) {
  try {
    await fn();
    console.log(`  ok   ${name}`);
  } catch (e) {
    failed++;
    console.log(`  FEHL ${name}\n       ${(e as Error).message.split('\n').join('\n       ')}`);
  }
}

const targets: Record<SqlDialect, { port: number; user: string; password: string; schema: string }> = {
  mysql: { port: 15306, user: 'root', password: 'dbviewer-test', schema: '' },
  postgres: { port: 15432, user: 'postgres', password: 'dbviewer-test', schema: 'public' },
  mssql: { port: 15433, user: 'sa', password: 'Dbviewer-Test1', schema: 'dbo' },
};

function input(dialect: SqlDialect, readOnly = false): ConnectionInput {
  const t = targets[dialect];
  return {
    name: dialect,
    dialect,
    host: '127.0.0.1',
    port: t.port,
    user: t.user,
    password: t.password,
    database: 'shop',
    options: { readOnly, ...(dialect === 'mssql' ? { trustServerCertificate: true } : {}) },
  };
}

/** Spaltenname mit Anführungszeichen, eckiger Klammer und Backtick (muss in jedem Dialekt richtig verdoppelt werden) */

async function main() {
  assertTestContainers(Object.entries(targets).map(([name, t]) => ({ name, host: '127.0.0.1', port: t.port })));
  const m = new Manager(store, undefined, 0);

  for (const dialect of ['mysql', 'postgres', 'mssql'] as const) {
    console.log(`\n${dialect}`);
    const c = await store.save(input(dialect));
    const ro = await store.save(input(dialect, true));
    const schema = targets[dialect].schema;
    const ref = (name: string, kind: 'table' | 'view' = 'table'): ObjectRef => ({ connectionId: c.id, database: 'shop', schema, name, kind });
    const { sessionId } = await m.openSession(c.id, 'shop');
    const q = async (sql: string) => {
      const r = await m.runQuery(sessionId, [{ sql, offset: 0 }], 100);
      if (r.statements[0]?.error) throw new Error(`${sql}: ${r.statements[0].error}`);
      return r.results[0]?.rows ?? [];
    };
    const t = dialect === 'mssql' ? 'dbo.edit_test' : 'edit_test';
    for (const s of ddl[dialect]) await q(s);
    const row = async (id: number) => (await q(`SELECT name, betrag, aktiv, notiz, erstellt FROM ${t} WHERE id = ${id}`))[0];
    const apply = (name: string, changes: RowChange[], preview = false) => m.applyChanges({ object: ref(name), changes, preview });

    await step('Vorschau: Anweisungen mit Werten, nichts geändert', async () => {
      const r = await apply('edit_test', [{ kind: 'update', key: { id: 1 }, values: { name: 'EINS' }, original: { name: 'eins' } }], true);
      assert.equal(r.applied, 0);
      assert.equal(r.statements.length, 1);
      assert.match(r.statements[0], /UPDATE .*edit_test.* SET .*name.* = N?'EINS' WHERE .*id.* = 1 AND .*name.* = N?'eins';/);
      assert.equal((await row(1))[0], 'eins');
    });
    await step('Ändern: Text, Zahl, NULL, Datum, Wahrheitswert', async () => {
      const r = await apply('edit_test', [
        {
          kind: 'update',
          key: { id: 1 },
          values: { name: 'eins neu', betrag: '9.99', notiz: null, erstellt: '2025-03-04 05:06:07', aktiv: dialect === 'mysql' ? 0 : false },
          original: { name: 'eins', betrag: '1.50', notiz: 'a', erstellt: null, aktiv: dialect === 'mysql' ? 1 : true },
        },
      ]);
      assert.equal(r.applied, 1);
      const [name, betrag, aktiv, notiz, erstellt] = await row(1);
      assert.equal(name, 'eins neu');
      assert.equal(String(betrag), '9.99');
      assert.equal(notiz, null);
      assert.equal(String(erstellt).slice(0, 19), '2025-03-04 05:06:07');
      assert.ok(aktiv === false || aktiv === 0, `aktiv = ${aktiv}`);
    });
    await step('gleicher Wert noch einmal: gilt als getroffen (MySQL zählt sonst 0)', async () => {
      await apply('edit_test', [{ kind: 'update', key: { id: 1 }, values: { name: 'eins neu' }, original: { name: 'eins neu' } }]);
    });
    await step('Wert mit Anführungszeichen und Semikolon bleibt ein Wert', async () => {
      const evil = "x'); DROP TABLE edit_test; --";
      await apply('edit_test', [{ kind: 'update', key: { id: 2 }, values: { notiz: evil }, original: { notiz: null } }]);
      assert.equal((await row(2))[3], evil);
    });
    await step('inzwischen geändert: Fehler, NICHTS gespeichert (auch die andere Änderung nicht)', async () => {
      await q(`UPDATE ${t} SET name = ${dialect === 'mssql' ? "N'" : "'"}zwei anders' WHERE id = 2`);
      await assert.rejects(
        apply('edit_test', [
          { kind: 'update', key: { id: 3 }, values: { notiz: 'soll nicht bleiben' }, original: { notiz: 'c' } },
          { kind: 'update', key: { id: 2 }, values: { name: 'zwei neu' }, original: { name: 'zwei' } },
        ]),
        /keine Zeile getroffen.*nichts gespeichert/,
      );
      assert.equal((await row(3))[3], 'c');
      assert.equal((await row(2))[0], 'zwei anders');
    });
    await step('eindeutiger Index verletzt: Fehler der Datenbank, nichts gespeichert', async () => {
      await assert.rejects(
        apply('edit_test', [
          { kind: 'delete', key: { id: 3 } },
          { kind: 'update', key: { id: 1 }, values: { name: 'zwei anders' }, original: { name: 'eins neu' } },
        ]),
        /duplicate|unique|UNIQUE|doppelt|eindeutig/i,
      );
      assert.equal(Number((await q(`SELECT COUNT(*) FROM ${t}`))[0][0]), 3);
    });
    await step('Einfügen (Rest = Standardwert) und Löschen', async () => {
      await apply('edit_test', [
        { kind: 'insert', values: { id: 4, name: 'vier' } },
        { kind: 'delete', key: { id: 3 } },
      ]);
      const r = await row(4);
      assert.equal(r[0], 'vier');
      assert.ok(r[2] === true || r[2] === 1, 'Standardwert aktiv');
      assert.equal(Number((await q(`SELECT COUNT(*) FROM ${t} WHERE id = 3`))[0][0]), 0);
    });
    await step('Einfügen in Tabelle mit Identität ohne Schlüsselwert', async () => {
      await apply('edit_ident', [{ kind: 'insert', values: { name: 'a' } }, { kind: 'insert', values: { name: 'b' } }]);
      const rows = await q(`SELECT id, name FROM ${dialect === 'mssql' ? 'dbo.' : ''}edit_ident ORDER BY id`);
      assert.deepEqual(rows.map((r) => [Number(r[0]), r[1]]), [
        [1, 'a'],
        [2, 'b'],
      ]);
    });
    const tbl = (name: string) => (dialect === 'mssql' ? `dbo.${name}` : name);
    await step('mehrspaltiger Schlüssel: ändern (auch eine Schlüsselspalte) und löschen', async () => {
      await apply('edit_pos', [{ kind: 'update', key: { bestellung: 1, pos: 2 }, values: { pos: 3, menge: 7 }, original: { pos: 2, menge: 5 } }]);
      await apply('edit_pos', [{ kind: 'delete', key: { bestellung: 1, pos: 1 } }]);
      const rows = await q(`SELECT bestellung, pos, menge FROM ${tbl('edit_pos')} ORDER BY bestellung, pos`);
      assert.deepEqual(
        rows.map((r) => r.map(Number)),
        [
          [1, 3, 7],
          [2, 2, 5],
        ],
      );
    });
    await step('ohne Primärschlüssel: eindeutiger Index ohne NULL dient als Schlüssel', async () => {
      await apply('edit_uq', [
        { kind: 'update', key: { code: 'CH' }, values: { name: 'Schweiz neu' }, original: { name: 'Schweiz' } },
        { kind: 'delete', key: { code: 'DE' } },
      ]);
      assert.deepEqual(await q(`SELECT code, name FROM ${tbl('edit_uq')} ORDER BY code`), [['CH', 'Schweiz neu']]);
    });
    await step('leere neue Zeile: nur Standardwerte (DEFAULT VALUES bzw. () VALUES ())', async () => {
      await apply('edit_def', [{ kind: 'insert', values: {} }]);
      const rows = await q(`SELECT id, status FROM ${tbl('edit_def')}`);
      assert.deepEqual(
        rows.map((r) => [Number(r[0]), r[1]]),
        [[1, 'neu']],
      );
    });
    await step('Spaltenname mit Anführungszeichen, eckiger Klammer und Backtick', async () => {
      await apply('edit_odd', [
        { kind: 'update', key: { id: 1 }, values: { [ODD]: 'neu' }, original: { [ODD]: 'alt' } },
        { kind: 'insert', values: { id: 2, [ODD]: 'zwei' } },
      ]);
      const rows = await q(`SELECT * FROM ${tbl('edit_odd')} ORDER BY id`);
      assert.deepEqual(
        rows.map((r) => [Number(r[0]), r[1]]),
        [
          [1, 'neu'],
          [2, 'zwei'],
        ],
      );
    });
    await step('Zeile gibt es nicht mehr: Fehler', async () => {
      await assert.rejects(apply('edit_test', [{ kind: 'delete', key: { id: 99 } }]), /keine Zeile getroffen/);
    });
    await step('Tabelle ohne Primärschlüssel: Ändern abgelehnt', async () => {
      await assert.rejects(apply('edit_nopk', [{ kind: 'update', key: { x: 1 }, values: { x: 2 } }]), /keinen Primärschlüssel/);
    });
    await step('View und „Nur lesen“: abgelehnt', async () => {
      await assert.rejects(m.applyChanges({ object: ref('v_umsatz', 'view'), changes: [{ kind: 'delete', key: { ort: 'Bern' } }], preview: false }), /Views/);
      await assert.rejects(
        m.applyChanges({ object: { ...ref('edit_test'), connectionId: ro.id }, changes: [{ kind: 'delete', key: { id: 1 } }], preview: false }),
        /Nur lesen/,
      );
      assert.equal(Number((await q(`SELECT COUNT(*) FROM ${t} WHERE id = 1`))[0][0]), 1);
    });
    await m.closeSession(sessionId);
  }

  await m.shutdown();
  console.log(failed ? `\n${failed} Fehler` : '\nalles ok');
  process.exit(failed ? 1 : 0);
}

void main();

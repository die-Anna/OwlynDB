/* PostgreSQL-Treiber: Indexspalten mit Großbuchstaben, Fremdschlüssel auf Partitionen, DDL (Views mit Optionen,
   Matview-Indizes, GENERATED/IDENTITY, PARTITION BY, Unique-Index mit fremdem Fremdschlüssel), Objektsuche ohne
   Partitionen, maxRows 0 = alles ausführen, bytea in der Anzeige gekürzt, Abbrechen zwischen Cursor-Stapeln, Sperrfrist
   beim Speichern. Aufruf: npm run testdb:up, dann npm run test:postgres */
import assert from 'node:assert/strict';
import type { ResultColumn, TableDataRequest } from '../../shared/api-types';
import { createDriver, type MetaDriver, type Session } from '../drivers';
import type { ExportCell } from '../export';
import { assertTestContainers } from './guard';

const base = { host: '127.0.0.1', port: 15432, user: 'postgres', password: 'dbviewer-test' };
const DB = 'pg_review';

let failed = 0;
async function step(name: string, fn: () => Promise<void> | void) {
  const t0 = Date.now();
  try {
    await fn();
    console.log(`  ok   ${name} (${Date.now() - t0} ms)`);
  } catch (e) {
    failed++;
    console.log(`  FEHL ${name}\n       ${(e as Error).stack?.split('\n').slice(0, 4).join('\n       ')}`);
  }
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function run(s: Session, sql: string, maxRows = 100) {
  const r = await s.run([{ sql, offset: 0 }], maxRows);
  const bad = r.statements.find((x) => x.error);
  if (bad) throw new Error(`${bad.error}\n       bei: ${sql.slice(0, 120)}`);
  return r;
}

const ref = (name: string, kind: 'table' | 'view' = 'table'): TableDataRequest => ({
  object: { connectionId: '', database: DB, schema: 'public', name, kind },
  limit: 100,
  offset: 0,
  sort: [],
});

(async () => {
  assertTestContainers([{ name: 'postgres', host: base.host, port: base.port }]);
  const admin = createDriver('postgres', { ...base, database: 'postgres' });
  const as = await admin.openSession('postgres');
  await run(as, `DROP DATABASE IF EXISTS ${DB} WITH (FORCE)`);
  await run(as, `CREATE DATABASE ${DB}`);
  await as.close();
  await admin.close();

  const d: MetaDriver = createDriver('postgres', { ...base, database: DB });
  const s = await d.openSession(DB);
  console.log('\npostgres');

  await step('Testschema anlegen', async () => {
    for (const sql of [
      'CREATE TABLE "Customers" ("Id" int PRIMARY KEY, "Name" text, lower_name text, data bytea)',
      'CREATE INDEX ix_lower ON "Customers" ((lower("Name")))',
      'CREATE UNIQUE INDEX ux_customers_lower_name ON "Customers" (lower_name)',
      'CREATE TABLE orders (id int PRIMARY KEY, "customerId" int REFERENCES "Customers"("Id"), lname text REFERENCES "Customers"(lower_name))',
      "CREATE TABLE gen (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, a int, b int, total int GENERATED ALWAYS AS (a * b) STORED, note text DEFAULT 'x')",
      'CREATE TABLE gen2 (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)',
      'CREATE TABLE part (id int, k int, PRIMARY KEY (id, k), cust int REFERENCES "Customers"("Id")) PARTITION BY RANGE (k)',
      'CREATE TABLE part_1 PARTITION OF part FOR VALUES FROM (0) TO (10)',
      'CREATE TABLE part_2 PARTITION OF part FOR VALUES FROM (10) TO (20)',
      'CREATE VIEW v_cust WITH (security_invoker = true) AS SELECT "Id", "Name" FROM "Customers" WHERE "Id" > 0 WITH LOCAL CHECK OPTION',
      'CREATE MATERIALIZED VIEW mv_cust AS SELECT "Id", "Name" FROM "Customers"',
      'CREATE UNIQUE INDEX ux_mv ON mv_cust ("Id")',
      `INSERT INTO "Customers" VALUES (1, 'Anna', 'anna', decode(repeat('ab', 2000), 'hex')), (2, 'Jan', 'jan', NULL)`,
      'CREATE TABLE seen (n int)',
      'CREATE FUNCTION mark(i int) RETURNS int LANGUAGE plpgsql AS $$ BEGIN INSERT INTO seen VALUES (i); RETURN i; END $$',
    ])
      await run(s, sql);
  });

  await step('F006: Indexspalten roh („Id“ statt "Id"), Ausdrucks-Index als Text', async () => {
    const info = await d.describeTable(DB, 'public', 'Customers');
    const pk = info.indexes.find((i) => i.primary)!;
    assert.deepEqual(pk.columns, ['Id']);
    assert.deepEqual(info.indexes.find((i) => i.name === 'ux_customers_lower_name')!.columns, ['lower_name']);
    assert.match(info.indexes.find((i) => i.name === 'ix_lower')!.columns[0], /lower\("Name"\)/);
    const orders = await d.describeTable(DB, 'public', 'orders');
    assert.deepEqual(orders.foreignKeys.map((f) => f.columns[0]).sort(), ['customerId', 'lname']);
  });

  await step('F093: Fremdschlüssel partitionierter Tabellen ohne die Kopien je Partition', async () => {
    const part = await d.describeTable(DB, 'public', 'part');
    assert.equal(part.foreignKeys.length, 1, JSON.stringify(part.foreignKeys));
    const cust = await d.describeTable(DB, 'public', 'Customers');
    assert.deepEqual(
      cust.referencedBy.map((r) => r.table).sort(),
      ['orders', 'orders', 'part'],
      JSON.stringify(cust.referencedBy.map((r) => r.table)),
    );
  });

  await step('F264: Objektsuche ohne Partitionen', async () => {
    const hits = await d.searchObjects(DB, '%part%', 100);
    assert.deepEqual([...new Set(hits.map((h) => h.name))], ['part']);
  });

  await step('F097/F096/F265: Tabellen-DDL mit GENERATED, IDENTITY, Unique-Index trotz fremdem Fremdschlüssel, PARTITION BY', async () => {
    const gen = await d.getDdl(DB, 'public', 'gen', 'table');
    assert.match(gen, /"id" integer GENERATED ALWAYS AS IDENTITY/);
    assert.match(gen, /"total" integer GENERATED ALWAYS AS \(a \* b\) STORED/);
    assert.doesNotMatch(gen, /DEFAULT \(a \* b\)/);
    assert.match(gen, /"note" text DEFAULT 'x'::text/);
    assert.match(await d.getDdl(DB, 'public', 'gen2', 'table'), /GENERATED BY DEFAULT AS IDENTITY/);
    const cust = await d.getDdl(DB, 'public', 'Customers', 'table');
    assert.match(cust, /CREATE UNIQUE INDEX ux_customers_lower_name/);
    assert.match(cust, /CREATE INDEX ix_lower/);
    assert.doesNotMatch(cust, /CONSTRAINT "Customers_pkey".*\n[\s\S]*CREATE UNIQUE INDEX "Customers_pkey"/);
    const part = await d.getDdl(DB, 'public', 'part', 'table');
    assert.match(part, /\) PARTITION BY RANGE \(k\);/);
    assert.match(part, /CONSTRAINT "part_pkey" PRIMARY KEY \(id, k\)/);
  });

  await step('F094/F095: View-DDL mit Optionen und CHECK OPTION, Matview mit Indizes', async () => {
    const v = await d.getDdl(DB, 'public', 'v_cust', 'view');
    assert.match(v, /CREATE OR REPLACE VIEW "public"\."v_cust" WITH \(security_invoker=true\) AS/);
    assert.match(v, /WITH LOCAL CHECK OPTION;$/m);
    const mv = await d.getDdl(DB, 'public', 'mv_cust', 'view');
    assert.match(mv, /^CREATE MATERIALIZED VIEW/);
    assert.match(mv, /CREATE UNIQUE INDEX ux_mv ON public\.mv_cust/);
  });

  await step('F100: maxRows 0 führt die ganze Anweisung aus (Einspielen, Kopieren)', async () => {
    await run(s, 'SELECT mark(n) FROM generate_series(1, 500) AS n', 0);
    assert.equal(Number((await run(s, 'SELECT COUNT(*) FROM seen')).results[0].rows[0][0]), 500);
  });

  await step('F091: bytea in Abfrage-Tab und Tabellenansicht gekürzt (binaryCut), Export vollständig', async () => {
    const r = await run(s, 'SELECT data FROM "Customers" WHERE "Id" = 1');
    assert.equal(r.results[0].binaryCut, true);
    const cell = String(r.results[0].rows[0][0]);
    assert.ok(cell.startsWith('0xABAB'), cell.slice(0, 20));
    assert.match(cell, /… \(2000 Bytes\)$/);
    const t = await d.fetchTable({ ...ref('Customers'), where: '"Id" = 1' });
    assert.match(String(t.rows[0][3]), /^0xABAB.*\(2000 Bytes\)$/);
    assert.equal(await d.countTable({ ...ref('Customers'), where: '"Id" = 1' }), 1);
    const got: ExportCell[][] = [];
    await d.streamTable({ ...ref('Customers'), limit: 0, where: '"Id" = 1' }, { begin: async () => undefined, rows: async (b) => void got.push(...b) });
    assert.ok(Buffer.isBuffer(got[0][3]) && (got[0][3] as Buffer).length === 2000, 'Export: Binärwert vollständig');
  });

  await step('F101: Abbrechen während des Exports greift zwischen zwei Cursor-Stapeln', async () => {
    let batches = 0;
    const sink = {
      begin: async (_c: ResultColumn[]) => undefined,
      rows: async (_b: ExportCell[][]) => {
        batches++;
        await sleep(200);
      },
    };
    const pending = s.streamResult({ sql: "SELECT n, repeat('x', 100) FROM generate_series(1, 20000) AS n", offset: 0 }, 0, sink);
    await sleep(300);
    const t0 = Date.now();
    await s.cancel();
    await assert.rejects(pending, /Abgebrochen/);
    assert.ok(Date.now() - t0 < 2000, `Abbruch brauchte ${Date.now() - t0} ms`);
    assert.ok(batches < 8, `${batches} Stapel trotz Abbruch`);
    assert.equal(Number((await run(s, 'SELECT 1')).results[0].rows[0][0]), 1);
  });

  await step('F099: Speichern wartet nicht unbegrenzt auf eine fremde Zeilensperre', async () => {
    const other = await d.openSession(DB);
    try {
      await run(other, 'BEGIN');
      await run(other, `UPDATE "Customers" SET "Name" = 'gesperrt' WHERE "Id" = 2`);
      const t0 = Date.now();
      await assert.rejects(
        d.applyWrites(DB, [{ sql: 'UPDATE "Customers" SET "Name" = $1 WHERE "Id" = $2', params: ['neu', 2], expect: 1, label: 'Ändern (Id = 2)' }]),
        /gesperrt/,
      );
      assert.ok(Date.now() - t0 < 15000);
      await run(other, 'ROLLBACK');
    } finally {
      await other.close();
    }
    assert.deepEqual(await d.applyWrites(DB, [{ sql: 'UPDATE "Customers" SET "Name" = $1 WHERE "Id" = $2', params: ['neu', 2], expect: 1, label: 'Ändern' }]), [1]);
  });

  await s.close();
  await d.close();
  const admin2 = createDriver('postgres', { ...base, database: 'postgres' });
  const as2 = await admin2.openSession('postgres');
  await run(as2, `DROP DATABASE IF EXISTS ${DB} WITH (FORCE)`);
  await as2.close();
  await admin2.close();
  console.log(failed ? `\n${failed} Fehler` : '\nalles ok');
  process.exit(failed ? 1 : 0);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});

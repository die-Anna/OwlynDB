/* Prozeduren, Funktionen, Trigger: auflisten, Text, Ändern über das Editor-Skript, Dump mit Rückweg.
   Vorher: npm run testdb:up (und einmal npm run test:drivers für die Datenbank shop). Aufruf: npm run test:routines */
import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { ConnectionInput, SqlDialect, JobStatus } from '../../shared/api-types';
import { splitSql } from '../../shared/sql-splitter';
import { ConnectionStore } from '../connection-store';
import { Manager } from '../manager';
import { assertTestContainers } from './guard';

const dir = mkdtempSync(path.join(os.tmpdir(), 'dbv-rt-'));
const store = new ConnectionStore(path.join(dir, 'c.json'), { encrypt: (s) => 'x' + s, decrypt: (s) => s.slice(1) });
let nextFile = '';
const m = new Manager(store, { pickFile: async () => null, saveFile: async () => nextFile, showInFolder: () => undefined }, 0);

let failed = 0;
async function step(name: string, fn: () => Promise<unknown>) {
  try {
    await fn();
    console.log(`  ok   ${name}`);
  } catch (e) {
    failed++;
    console.log(`  FEHL ${name}\n       ${(e as Error).message.split('\n').join('\n       ')}`);
  }
}

const targets: Record<SqlDialect, { port: number; user: string; password: string; schema: string }> = {
  mysql: { port: 15306, user: 'root', password: 'dbviewer-test', schema: '' },
  postgres: { port: 15432, user: 'postgres', password: 'dbviewer-test', schema: 'public' },
  mssql: { port: 15433, user: 'sa', password: 'Dbviewer-Test1', schema: 'dbo' },
};

function input(dialect: SqlDialect): ConnectionInput {
  const t = targets[dialect];
  return {
    name: dialect,
    dialect,
    host: '127.0.0.1',
    port: t.port,
    user: t.user,
    password: t.password,
    database: dialect === 'postgres' ? 'postgres' : undefined,
    options: dialect === 'mssql' ? { trustServerCertificate: true } : {},
  };
}

/** Testobjekte: Zieltabelle mit Trigger, der in eine Protokolltabelle schreibt; Funktion; Prozedur */
const setup: Record<SqlDialect, string[]> = {
  mysql: [
    'DROP TRIGGER IF EXISTS rt_trg',
    'DROP FUNCTION IF EXISTS rt_doppelt',
    'DROP PROCEDURE IF EXISTS rt_proc',
    'DROP TABLE IF EXISTS rt_ziel, rt_log',
    'CREATE TABLE rt_ziel (id int PRIMARY KEY, n int)',
    'CREATE TABLE rt_log (id int AUTO_INCREMENT PRIMARY KEY, msg varchar(50))',
    'CREATE FUNCTION rt_doppelt(x INT) RETURNS INT DETERMINISTIC RETURN x * 2',
    'CREATE PROCEDURE rt_proc(IN a INT) BEGIN SELECT a; SELECT a + 1; END',
    "CREATE TRIGGER rt_trg AFTER INSERT ON rt_ziel FOR EACH ROW INSERT INTO rt_log (msg) VALUES (CONCAT('neu ', NEW.id))",
    'INSERT INTO rt_ziel VALUES (1, 10), (2, 20)',
  ],
  postgres: [
    'DROP TABLE IF EXISTS public.rt_ziel, public.rt_log CASCADE',
    'DROP FUNCTION IF EXISTS public.rt_doppelt(int), public.rt_doppelt(text), public.rt_trgf()',
    'DROP PROCEDURE IF EXISTS public.rt_proc(int)',
    'CREATE TABLE public.rt_ziel (id int PRIMARY KEY, n int)',
    'CREATE TABLE public.rt_log (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, msg varchar(50))',
    'CREATE FUNCTION public.rt_doppelt(x int) RETURNS int LANGUAGE sql AS $$ SELECT x * 2 $$',
    'CREATE FUNCTION public.rt_doppelt(x text) RETURNS text LANGUAGE sql AS $$ SELECT x || x $$',
    "CREATE PROCEDURE public.rt_proc(a int) LANGUAGE plpgsql AS $$ BEGIN RAISE NOTICE 'a = %', a; END $$",
    "CREATE FUNCTION public.rt_trgf() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN INSERT INTO public.rt_log (msg) VALUES ('neu ' || NEW.id); RETURN NEW; END $$",
    'CREATE TRIGGER rt_trg AFTER INSERT ON public.rt_ziel FOR EACH ROW EXECUTE FUNCTION public.rt_trgf()',
    'INSERT INTO public.rt_ziel VALUES (1, 10), (2, 20)',
  ],
  mssql: [
    "IF OBJECT_ID('dbo.rt_ziel') IS NOT NULL DROP TABLE dbo.rt_ziel",
    "IF OBJECT_ID('dbo.rt_log') IS NOT NULL DROP TABLE dbo.rt_log",
    "IF OBJECT_ID('dbo.rt_doppelt') IS NOT NULL DROP FUNCTION dbo.rt_doppelt",
    "IF OBJECT_ID('dbo.rt_proc') IS NOT NULL DROP PROCEDURE dbo.rt_proc",
    'CREATE TABLE dbo.rt_ziel (id int PRIMARY KEY, n int)',
    'CREATE TABLE dbo.rt_log (id int IDENTITY(1,1) PRIMARY KEY, msg nvarchar(50))',
    'CREATE FUNCTION dbo.rt_doppelt(@x int) RETURNS int AS BEGIN RETURN @x * 2 END',
    'CREATE PROCEDURE dbo.rt_proc @a int AS BEGIN SELECT @a; SELECT @a + 1; END',
    "CREATE TRIGGER dbo.rt_trg ON dbo.rt_ziel AFTER INSERT AS INSERT INTO dbo.rt_log (msg) SELECT CONCAT('neu ', id) FROM inserted",
    'INSERT INTO dbo.rt_ziel VALUES (1, 10), (2, 20)',
  ],
};

async function waitJob(id: string): Promise<JobStatus> {
  for (;;) {
    const s = await m.jobStatus(id);
    if (s.state !== 'running') return s;
    await new Promise((r) => setTimeout(r, 100));
  }
}

async function main() {
  assertTestContainers(Object.entries(targets).map(([name, t]) => ({ name, host: '127.0.0.1', port: t.port })));

  for (const dialect of ['mysql', 'postgres', 'mssql'] as const) {
    console.log(`\n${dialect}`);
    const c = await store.save(input(dialect));
    const schema = targets[dialect].schema;
    const t = (n: string) => (dialect === 'mysql' ? n : `${schema}.${n}`);
    const run = async (db: string, sql: string) => {
      const { sessionId } = await m.openSession(c.id, db);
      try {
        const r = await m.runQuery(sessionId, [{ sql, offset: 0 }], 100);
        if (r.statements[0]?.error) throw new Error(`${sql.slice(0, 80)}: ${r.statements[0].error}`);
        return r;
      } finally {
        await m.closeSession(sessionId);
      }
    };
    for (const sql of setup[dialect]) await run('shop', sql);

    await step('auflisten: Prozedur, Funktion(en), Trigger mit Tabelle', async () => {
      const list = await m.listRoutines(c.id, 'shop', schema);
      const mine = list.filter((r) => r.name.startsWith('rt_'));
      const kinds = mine.map((r) => `${r.kind}:${r.name}${r.table ? '@' + r.table : ''}${r.args !== undefined ? '(' + r.args + ')' : ''}`).sort();
      const expected =
        dialect === 'postgres'
          ? ['function:rt_doppelt(x integer)', 'function:rt_doppelt(x text)', 'function:rt_trgf()', 'procedure:rt_proc(IN a integer)', 'trigger:rt_trg@rt_ziel']
          : ['function:rt_doppelt', 'procedure:rt_proc', 'trigger:rt_trg@rt_ziel'];
      assert.deepEqual(kinds, expected);
      // Routinen aus den Seeds sind auch da
      assert.ok(list.some((r) => r.name === (dialect === 'postgres' ? 'kunden_anzahl' : 'kunden_von')));
    });

    await step('Text im Editor: Ändern-Skript passt zum Datenbanktyp, Überladungen getrennt', async () => {
      const base = { connectionId: c.id, database: 'shop', schema };
      const proc = await m.getRoutineDdl({ ...base, name: 'rt_proc', kind: 'procedure', ...(dialect === 'postgres' ? { args: 'IN a integer' } : {}) });
      const trg = await m.getRoutineDdl({ ...base, name: 'rt_trg', kind: 'trigger', table: 'rt_ziel' });
      if (dialect === 'mysql') {
        assert.match(proc, /^-- MySQL kennt kein CREATE OR REPLACE[\s\S]*-- DROP PROCEDURE IF EXISTS `rt_proc`;\nDELIMITER ;;\nCREATE[\s\S]*PROCEDURE `rt_proc`[\s\S]*END ;;\nDELIMITER ;\n$/);
        assert.match(trg, /CREATE[\s\S]*TRIGGER `rt_trg` AFTER INSERT ON `rt_ziel`/);
      } else if (dialect === 'postgres') {
        assert.match(proc, /^CREATE OR REPLACE PROCEDURE public\.rt_proc\((IN )?a integer\)/);
        const textVariant = await m.getRoutineDdl({ ...base, name: 'rt_doppelt', kind: 'function', args: 'x text' });
        assert.match(textVariant, /x \|\| x/);
        // Schema nur, wenn es nicht im Suchpfad liegt
        assert.match(trg, /-- DROP TRIGGER IF EXISTS rt_trg ON public\.rt_ziel;\nCREATE TRIGGER rt_trg AFTER INSERT ON (public\.)?rt_ziel/);
      } else {
        assert.match(proc, /^CREATE OR ALTER PROCEDURE dbo\.rt_proc[\s\S]*\nGO\n$/);
        assert.match(trg, /^CREATE OR ALTER TRIGGER dbo\.rt_trg/);
      }
    });

    await step('Editor-Skript ausführen ändert die Routine (wie F5 im Abfrage-Tab)', async () => {
      const base = { connectionId: c.id, database: 'shop', schema };
      let script = await m.getRoutineDdl({ ...base, name: 'rt_doppelt', kind: 'function', ...(dialect === 'postgres' ? { args: 'x integer' } : {}) });
      script = script.replace(/\* 2/, '* 3');
      // MySQL: erst die alte Fassung löschen (die Zeile steht auskommentiert im Skript)
      if (dialect === 'mysql') script = script.replace('-- DROP FUNCTION', 'DROP FUNCTION');
      const { sessionId } = await m.openSession(c.id, 'shop');
      try {
        const stmts = splitSql(script, dialect).map((s) => ({ sql: s.sql, offset: s.start }));
        const r = await m.runQuery(sessionId, stmts, 10);
        assert.ok(!r.statements.some((s) => s.error), r.statements.find((s) => s.error)?.error);
        const v = await m.runQuery(sessionId, [{ sql: `SELECT ${t('rt_doppelt')}(5)`, offset: 0 }], 10);
        assert.equal(Number(v.results[0].rows[0][0]), 15);
      } finally {
        await m.closeSession(sessionId);
      }
    });

    await step('Dump mit Routinen und Rückweg: Trigger kommt mit, löst beim Einspielen aber nicht aus', async () => {
      const target = `rt_${dialect}`;
      if (dialect === 'mysql') await run('shop', `DROP DATABASE IF EXISTS ${target}`);
      if (dialect === 'postgres') await run('postgres', `DROP DATABASE IF EXISTS ${target} WITH (FORCE)`);
      if (dialect === 'mssql') await run('master', `IF DB_ID('${target}') IS NOT NULL BEGIN ALTER DATABASE [${target}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [${target}]; END`);
      nextFile = path.join(dir, `${target}.sql`);
      const id = await m.startDump({
        connectionId: c.id,
        database: 'shop',
        tables: [{ schema, name: 'rt_log' }, { schema, name: 'rt_ziel' }],
        views: [],
        structure: true,
        data: true,
        dropFirst: true,
        routines: true,
        targetDialect: dialect,
        rowsPerInsert: 100,
        baseName: 'x',
      });
      const d = await waitJob(id!);
      assert.equal(d.state, 'done', d.error);
      const imp = await waitJob(
        await m.startImport({ connectionId: c.id, database: target, createDatabase: true, file: nextFile, stopOnError: true, transaction: dialect !== 'mysql', skipUse: true }),
      );
      assert.equal(imp.state, 'done', imp.error);
      const list = await m.listRoutines(c.id, target, schema);
      for (const n of ['rt_doppelt', 'rt_proc', 'rt_trg']) assert.ok(list.some((r) => r.name === n), `${n} fehlt im Ziel`);
      // zwei Protokollzeilen aus der Quelle – der Trigger darf beim Einspielen nicht noch zwei schreiben
      assert.equal(Number((await run(target, `SELECT COUNT(*) FROM ${t('rt_log')}`)).results[0].rows[0][0]), 2);
      await run(target, `INSERT INTO ${t('rt_ziel')} VALUES (3, 30)`);
      assert.equal(Number((await run(target, `SELECT COUNT(*) FROM ${t('rt_log')}`)).results[0].rows[0][0]), 3, 'Trigger im Ziel aktiv');
      assert.equal(Number((await run(target, `SELECT ${t('rt_doppelt')}(4)`)).results[0].rows[0][0]), 12, 'geänderte Funktion kam mit');
    });
  }

  await m.shutdown();
  console.log(failed ? `\n${failed} Fehler` : '\nalles ok');
  process.exit(failed ? 1 : 0);
}

void main();

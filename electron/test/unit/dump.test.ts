const col = (dataType: string, extra: Partial<ColumnInfo> = {}): ColumnInfo => ({ name: 'c', dataType, nullable: true, defaultValue: null, primaryKey: false, autoIncrement: false, ...extra });
const info = (columns: ColumnInfo[], extra: Partial<TableInfo> = {}): TableInfo => ({ columns, indexes: [], foreignKeys: [], referencedBy: [], ...extra });

test('F012: PostgreSQL numeric ohne Genauigkeit wird nicht zu decimal(18,0)', () => {
  const notes: string[] = [];
  assert.equal(mapType('postgres', col('numeric'), 'mysql', false, (m) => notes.push(m)), 'decimal(65,30)');
  assert.equal(mapType('postgres', col('numeric'), 'mssql', false), 'decimal(38,18)');
  assert.equal(mapType('postgres', col('numeric(12,2)'), 'mysql', false), 'decimal(12,2)');
  assert.equal(notes.length, 1);
});

test('F120: bigint unsigned AUTO_INCREMENT → PostgreSQL bigint (Identität geht nicht auf numeric)', () => {
  assert.equal(mapType('mysql', col('bigint unsigned', { autoIncrement: true }), 'postgres', true), 'bigint');
  assert.equal(mapType('mysql', col('bigint unsigned'), 'postgres', true), 'numeric(20,0)');
  assert.equal(columnSql('mysql', 'postgres', col('bigint unsigned', { autoIncrement: true, nullable: false }), 'bigint', [], 't'), 'c bigint GENERATED BY DEFAULT AS IDENTITY');
});


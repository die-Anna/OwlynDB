test('F011/F034: MySQL- und MariaDB-Standardwerte in SQL-Form (mysqlDefault)', () => {
  // MySQL 8: Text ohne Anführungszeichen, Ausdrücke mit DEFAULT_GENERATED
  assert.equal(mysqlDefault('Bern', '', 'varchar(60)', false), "'Bern'");
  assert.equal(mysqlDefault('', '', 'varchar(60)', false), "''");
  assert.equal(mysqlDefault('0', '', 'int', false), '0');
  assert.equal(mysqlDefault('1.5', '', 'decimal(5,2)', false), '1.5');
  assert.equal(mysqlDefault('12', '', 'varchar(5)', false), "'12'");
  assert.equal(mysqlDefault('CURRENT_TIMESTAMP', 'DEFAULT_GENERATED', 'timestamp', false), 'CURRENT_TIMESTAMP');
  assert.equal(mysqlDefault('CURRENT_TIMESTAMP(3)', 'DEFAULT_GENERATED on update CURRENT_TIMESTAMP(3)', 'datetime(3)', false), 'CURRENT_TIMESTAMP(3)');
  assert.equal(mysqlDefault('uuid()', 'DEFAULT_GENERATED', 'char(36)', false), '(uuid())');
  assert.equal(mysqlDefault('curdate()', 'DEFAULT_GENERATED', 'date', false), '(curdate())');
  assert.equal(mysqlDefault("b'1'", '', 'bit(1)', false), "b'1'");
  assert.equal(mysqlDefault("O'Brien", '', 'varchar(60)', false), "'O''Brien'");
  // MySQL 5.7: CURRENT_TIMESTAMP ohne Merkmal
  assert.equal(mysqlDefault('CURRENT_TIMESTAMP', '', 'datetime', false), 'CURRENT_TIMESTAMP');
  assert.equal(mysqlDefault(null, '', 'int', false), null);
  // MariaDB: Literale schon in SQL-Form, Ausdrücke bloß
  assert.equal(mysqlDefault("'Bern'", '', 'varchar(60)', true), "'Bern'");
  assert.equal(mysqlDefault("''", '', 'varchar(60)', true), "''");
  assert.equal(mysqlDefault('NULL', '', 'varchar(60)', true), 'NULL');
  assert.equal(mysqlDefault('0', '', 'int', true), '0');
  assert.equal(mysqlDefault('current_timestamp()', '', 'timestamp', true), 'current_timestamp()');
  assert.equal(mysqlDefault('uuid()', '', 'char(36)', true), '(uuid())');
});

test('F011/F034/F121: Standardwerte im Ziel – Text, Ausdruck, Sequenz', () => {
  const w: string[] = [];
  // MariaDB-Quelle: 'Bern' bleibt 'Bern', auch im anderen Typ
  assert.equal(columnSql('mysql', 'mysql', col('varchar(60)', { defaultValue: "'Bern'" }), 'varchar(60)', w, 't'), "`c` varchar(60) NULL DEFAULT 'Bern'");
  assert.equal(columnSql('mysql', 'postgres', col('varchar(60)', { defaultValue: "'Bern'" }), 'varchar(60)', w, 't'), "c varchar(60) NULL DEFAULT 'Bern'");
  assert.equal(columnSql('mysql', 'mssql', col('varchar(60)', { defaultValue: "''" }), 'nvarchar(60)', w, 't'), "[c] nvarchar(60) NULL DEFAULT N''");
  // Ausdruck: Datum und UUID übersetzt, Unbekanntes mit Hinweis weggelassen
  assert.equal(columnSql('mysql', 'postgres', col('date', { defaultValue: '(curdate())' }), 'date', w, 't'), 'c date NULL DEFAULT CURRENT_DATE');
  assert.equal(columnSql('mysql', 'mssql', col('char(36)', { defaultValue: '(uuid())' }), 'uniqueidentifier', w, 't'), '[c] uniqueidentifier NULL DEFAULT NEWID()');
  assert.equal(columnSql('postgres', 'mysql', col('uuid', { defaultValue: 'gen_random_uuid()' }), 'char(36)', w, 't'), '`c` char(36) NULL DEFAULT (UUID())');
  assert.equal(w.length, 0);
  assert.equal(columnSql('mysql', 'postgres', col('int', { defaultValue: '(floor(rand() * 10))' }), 'integer', w, 't'), 'c integer NULL');
  assert.match(w[0], /nicht übernommen/);
  // Sequenz: gibt es im Ziel nicht – auch im selben Typ
  assert.equal(columnSql('mssql', 'mssql', col('int', { defaultValue: '(NEXT VALUE FOR [dbo].[seq])' }), 'int', w, 't'), '[c] int NULL');
  assert.match(w[1], /NEXT VALUE FOR/);
  assert.equal(columnSql('postgres', 'postgres', col('text', { defaultValue: "'B-' || nextval('s'::regclass)" }), 'text', w, 't'), 'c text NULL');
  // MySQL-Bitwert
  assert.equal(columnSql('mysql', 'postgres', col('bit(1)', { defaultValue: "b'1'" }), 'boolean', w, 't'), 'c boolean NULL DEFAULT true');
});

test('F014/F122: Werte – tinyint(1) bleibt Zahl, boolean nur bei boolean/bit, Buffer in boolean', () => {
  const my = valueConverter('mysql', 'tinyint(1)', 'tinyint(1)', true);
  assert.equal(my(2), '2');
  assert.equal(my(5), '5');
  assert.equal(my(true), '1');
  const pg = valueConverter('postgres', 'boolean', 'tinyint(1)', true);
  assert.equal(pg(2), 'true');
  assert.equal(pg(0), 'false');
  assert.equal(pg('t'), 'true');
  assert.equal(pg(Buffer.from([1])), 'true');
  assert.equal(pg(Buffer.from([0])), 'false');
  const ms = valueConverter('mssql', 'bit', 'boolean', false);
  assert.equal(ms(true), '1');
  assert.equal(ms('false'), '0');
  // leerer Binärwert
  assert.equal(valueConverter('mysql', 'longblob', 'bytea', false)(Buffer.alloc(0)), "X''");
  assert.equal(valueConverter('mssql', 'varbinary(max)', 'bytea', false)(Buffer.alloc(0)), '0x');
});

test('F110: Zeitpunkt mit Zone – MySQL ohne Zone, SQL Server mit +hh:mm, PostgreSQL unverändert', () => {
  const v = '2024-06-01 10:00:00+00';
  assert.equal(valueConverter('mysql', 'datetime(6)', 'timestamp with time zone', false)(v), "'2024-06-01 10:00:00'");
  // SQL Server: mit T (sprachneutral) und +hh:mm
  assert.equal(valueConverter('mssql', 'datetimeoffset(6)', 'timestamp with time zone', false)(v), "N'2024-06-01T10:00:00+00:00'");
  // aus SQL Server selbst kommt '… +00:00' mit Leerzeichen (cellFor) – ohne das Leerzeichen, sonst „Conversion failed“ beim Einspielen
  assert.equal(valueConverter('mssql', 'datetimeoffset(0)', 'datetimeoffset(0)', false)('2024-06-01 10:00:00 +00:00'), "N'2024-06-01T10:00:00+00:00'");
  assert.equal(valueConverter('mssql', 'datetimeoffset(7)', 'datetimeoffset(7)', false)('2024-06-01 10:00:00.1234567 +00:00'), "N'2024-06-01T10:00:00.1234567+00:00'");
  assert.equal(valueConverter('mysql', 'datetime(6)', 'datetimeoffset(0)', false)('2024-06-01 10:00:00 +00:00'), "'2024-06-01 10:00:00'");
  assert.equal(valueConverter('mssql', 'datetime2(3)', 'timestamp', false)('2024-06-01 10:00:00.123'), "N'2024-06-01T10:00:00.123'");
  assert.equal(valueConverter('mssql', 'date', 'date', false)('2024-06-01'), "N'2024-06-01'");
  assert.equal(valueConverter('postgres', 'timestamptz', 'timestamp with time zone', false)(v), `'${v}'`);
  assert.equal(valueConverter('mysql', 'datetime(6)', 'timestamp with time zone', false)('2024-06-01 12:00:00+02:00'), "'2024-06-01 12:00:00'");
});

test('F115/F116/F031: Indizes – Wortlaut im selben Typ, Teilindex/Ausdruck nur mit Hinweis, NULL in SQL Server', () => {
  const t = { name: 't', toName: 't', info: info([col('text', { name: 'email' }), col('int', { name: 'n', nullable: false })]), types: ['text', 'int'] };
  const w: string[] = [];
  // PostgreSQL → PostgreSQL: ab USING, inklusive WHERE
  assert.equal(
    indexSql('postgres', 'postgres', t, '"public"."t"', { name: 'ix', columns: ['lower(email)'], unique: true, primary: false, where: '(n > 0)', definition: 'USING btree (lower(email)) WHERE (n > 0)' }, w),
    'CREATE UNIQUE INDEX ix ON "public"."t" USING btree (lower(email)) WHERE (n > 0)',
  );
  assert.equal(indexSql('postgres', 'postgres', t, '"public"."t"', { name: 'uq', columns: ['email'], unique: true, primary: false, constraint: true }, w), 'ALTER TABLE "public"."t" ADD CONSTRAINT uq UNIQUE (email)');
  assert.equal(indexSql('mysql', 'mysql', t, '`t`', { name: 'ft', columns: ['email'], unique: false, primary: false, kind: 'FULLTEXT', definition: '(`email`)' }, w), 'CREATE FULLTEXT INDEX `ft` ON `t` (`email`)');
  assert.equal(w.length, 0);
  // anderer Typ: Ausdruck und Teilindex fallen weg
  assert.equal(indexSql('postgres', 'mysql', t, '`t`', { name: 'ix', columns: ['lower(email)'], unique: true, primary: false }, w), null);
  assert.equal(indexSql('postgres', 'mysql', t, '`t`', { name: 'ix', columns: ['email'], unique: true, primary: false, where: '(n > 0)' }, w), null);
  assert.equal(w.length, 2);
  // SQL Server: eindeutig mit NULL-Spalte → gefiltert
  assert.equal(indexSql('mysql', 'mssql', t, '[dbo].[t]', { name: 'ix', columns: ['email', 'n'], unique: true, primary: false }, w), 'CREATE UNIQUE INDEX [ix] ON [dbo].[t] ([email], [n]) WHERE [email] IS NOT NULL');
  assert.match(w[2], /gefiltert/);
  // SQL-Server-Filter „IS NOT NULL“ auf den Indexspalten ist in MySQL/PostgreSQL die Vorgabe: Index ohne Filter
  assert.equal(indexSql('mssql', 'postgres', t, 't', { name: 'uq', columns: ['email'], unique: true, primary: false, where: '([email] IS NOT NULL)' }, w), 'CREATE UNIQUE INDEX t_uq ON t (email)');
  assert.equal(indexSql('mssql', 'mysql', t, '`t`', { name: 'uq', columns: ['email'], unique: true, primary: false, where: '([email] IS NOT NULL AND [n]>(0))' }, w), null);
  // MySQL: Text nur mit Präfix
  assert.equal(indexSql('postgres', 'mysql', t, '`t`', { name: 'ix', columns: ['email'], unique: false, primary: false }, w), 'CREATE INDEX `ix` ON `t` (`email`(255))');
});

test('F119/F035: Reihenfolge – Views hinter den Views, die sie benutzen; Tabellen hinter denen, auf die sie zeigen', () => {
  const views = [
    { name: 'a_top', ddl: 'CREATE VIEW a_top AS SELECT * FROM m_mid' },
    { name: 'm_mid', ddl: 'CREATE VIEW m_mid AS SELECT * FROM "z_base" JOIN t ON 1=1' },
    { name: 'z_base', ddl: 'CREATE VIEW z_base AS SELECT 1 AS x' },
    { name: 'other', ddl: 'CREATE VIEW other AS SELECT * FROM a_topping' },
  ];
  assert.deepEqual(orderByUse(views).map((v) => v.name), ['z_base', 'm_mid', 'a_top', 'other']);
  // Zyklus: bleibt stehen, nichts geht verloren
  const cyc = [
    { name: 'a', ddl: 'SELECT * FROM b' },
    { name: 'b', ddl: 'SELECT * FROM a' },
  ];
  assert.deepEqual(orderByUse(cyc).map((v) => v.name), ['b', 'a']);
  const fk = (refTable: string) => ({ name: 'fk', columns: ['x'], refSchema: 'public', refTable, refColumns: ['id'] });
  const tables = [
    { schema: 'public', name: 'positionen', info: info([], { foreignKeys: [fk('bestellungen')] }) },
    { schema: 'public', name: 'bestellungen', info: info([], { foreignKeys: [fk('kunden'), fk('bestellungen')] }) },
    { schema: 'public', name: 'kunden', info: info([]) },
    { schema: 'public', name: 'regionen', info: info([], { foreignKeys: [fk('woanders')] }) },
  ];
  assert.deepEqual(orderByRefs(tables, 'postgres').map((t) => t.name), ['kunden', 'bestellungen', 'positionen', 'regionen']);
});

test('F020/F036: SQL Server – gespeicherte ALTER-Definitionen werden CREATE OR ALTER (auch hinter Kommentaren)', () => {
  assert.equal(createOrAlter('ALTER PROCEDURE dbo.p AS SELECT 1'), 'CREATE OR ALTER PROCEDURE dbo.p AS SELECT 1');
  assert.equal(createOrAlter('-- create procedure im Kommentar\n/* noch */\nalter proc [p] as select 1'), '-- create procedure im Kommentar\n/* noch */\nCREATE OR ALTER proc [p] as select 1');
  assert.equal(createOrAlter('CREATE OR ALTER VIEW v AS SELECT 1'), 'CREATE OR ALTER VIEW v AS SELECT 1');
  assert.equal(createOrAlter('CREATE   TRIGGER t ON x AFTER INSERT AS SELECT 1'), 'CREATE OR ALTER   TRIGGER t ON x AFTER INSERT AS SELECT 1');
  const r = { name: 'p', kind: 'procedure' as const };
  assert.match(dumpScript('mssql', 'dbo', r, 'ALTER PROCEDURE dbo.p AS SELECT 1', false), /^CREATE OR ALTER PROCEDURE/);
  assert.match(editorScript('mssql', 'dbo', r, '-- Kopf\nALTER PROCEDURE dbo.p AS SELECT 1'), /^-- Kopf\nCREATE OR ALTER PROCEDURE/);
});

